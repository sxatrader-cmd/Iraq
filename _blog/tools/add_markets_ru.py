WHO = {"russia": ("России", VISA_ONLINE), "belarus": ("Беларуси", VISA_US), "ukraine": ("Украины", VISA_US)}


def run():
    sm = (A.ROOT / "sitemap.xml").read_text()
    for key, (who, visa) in WHO.items():
        A.VISA["ru"] = (visa[0], visa[1].format(who=who))
        u = A.build(key, "ru")
        f = A.ROOT / "ru" / A.M[key]["slug"] / "index.html"
        s = f.read_text()
        # Russian only: hreflang ru + x-default to itself (build() adds an English pair that doesn't exist)
        s = re.sub(r'<link rel="alternate" hreflang="[^"]*" href="[^"]*">\n?', "", s)
        s = s.replace(f'<link rel="canonical" href="{u}">\n',
                      f'<link rel="canonical" href="{u}">\n<link rel="alternate" hreflang="ru" href="{u}">\n'
                      f'<link rel="alternate" hreflang="x-default" href="{u}">\n', 1)
        f.write_text(s)
        sm = re.sub(r"  <url>\n    <loc>" + re.escape(u) + r"</loc>.*?</url>\n", "", sm, flags=re.S)
        sm = sm.replace("</urlset>", f"  <url>\n    <loc>{u}</loc>\n    <lastmod>{A.TODAY}</lastmod>\n    <changefreq>weekly</changefreq>\n"
                        f"    <priority>0.8</priority>\n    <xhtml:link rel=\"alternate\" hreflang=\"ru\" href=\"{u}\"/>\n"
                        f"    <xhtml:link rel=\"alternate\" hreflang=\"x-default\" href=\"{u}\"/>\n  </url>\n</urlset>")
        print("built", u)
    (A.ROOT / "sitemap.xml").write_text(sm)


if __name__ == "__main__":
    run()
